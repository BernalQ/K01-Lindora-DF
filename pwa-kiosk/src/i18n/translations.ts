export type TranslationKey = keyof (typeof dictionaries)['es']

export function translate(
  language: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const dictionary = dictionaries[language] ?? dictionaries.es
  let text: string = dictionary[key] ?? dictionaries.es[key] ?? key
  if (vars) {
    for (const [varName, value] of Object.entries(vars)) {
      text = text.replaceAll(`{{${varName}}}`, String(value))
    }
  }
  return text
}

